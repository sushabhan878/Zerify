async function seedCampaigns() {
  console.log(`Starting to seed ${CAMPAIGNS_DATA.length} comprehensive discovery campaigns...`);

  // Fetch all brands
  const brandProfiles = await prisma.brandProfile.findMany();
  if (brandProfiles.length === 0) {
    console.error('No brand profiles found in DB to link campaigns to.');
    return;
  }

  let createdCount = 0;
  for (let i = 0; i < CAMPAIGNS_DATA.length; i++) {
    const data = CAMPAIGNS_DATA[i];
    
    // Find matching brand or pick round-robin
    let brand = brandProfiles.find(
      (b) => b.companyName && b.companyName.toLowerCase() === data.companyName.toLowerCase()
    );
    if (!brand) {
      brand = brandProfiles[i % brandProfiles.length];
    }

    const uniqueSlug = `${data.slug}-${Math.random().toString(36).substring(2, 7)}`;
    const deadline = new Date();
    deadline.setDate(deadline.getDate() + data.daysAhead);

    const startDate = new Date();
    startDate.setDate(startDate.getDate() + data.daysAhead + 2);

    const endDate = new Date();
    endDate.setDate(endDate.getDate() + data.daysAhead + 30);

    // Create Campaign with Product, Requirement, and Deliverables
    await prisma.campaign.create({
      data: {
        brandProfileId: brand.id,
        title: data.title,
        slug: uniqueSlug,
        objective: data.objective,
        description: data.description,
        industry: data.industry,
        coverImageUrl: data.coverImageUrl,
        status: 'OPEN',
        platforms: data.platforms,
        budgetTotalAmount: data.budgetTotalAmount,
        budgetCurrency: data.budgetCurrency,
        budgetPaymentModel: data.budgetPaymentModel,
        budgetMinPerInfluencer: data.budgetMinPerInfluencer,
        budgetMaxPerInfluencer: data.budgetMaxPerInfluencer,
        targetParticipants: data.targetParticipants,
        maxParticipants: data.maxParticipants,
        autoCloseWhenFilled: true,
        contentGuidelines: data.contentGuidelines,
        applicationDeadline: deadline,
        startDate,
        endDate,
        publishedAt: new Date(),
        product: {
          create: {
            productName: data.product.productName,
            productType: data.product.productType,
            landingPageUrl: data.product.landingPageUrl,
            coverImageUrl: data.product.coverImageUrl,
            hasFreeProduct: data.product.hasFreeProduct,
            freeProductValue: data.product.freeProductValue,
            shippingDetails: data.product.shippingDetails,
            productInstructions: data.product.productInstructions,
          },
        },
        requirement: {
          create: {
            strictEligibility: data.requirement.strictEligibility,
            minFollowers: data.requirement.minFollowers,
            minEngagementRate: data.requirement.minEngagementRate,
            verifiedOnly: data.requirement.verifiedOnly,
            targetCountries: data.requirement.targetCountries,
            targetAgeGroup: data.requirement.targetAgeGroup,
            targetGenders: [],
            targetLanguages: ['English'],
            audienceCountries: data.requirement.targetCountries,
          },
        },
        deliverables: {
          create: data.deliverables.map((d) => ({
            type: d.type,
            quantity: d.quantity,
            requiredCta: d.requiredCta,
            mandatoryHashtags: d.mandatoryHashtags,
            mandatoryMentions: [],
            instructions: d.instructions,
            revisionLimit: d.revisionLimit,
          })),
        },
      },
    });

    createdCount++;
    console.log(`[${createdCount}/${CAMPAIGNS_DATA.length}] Created campaign: "${data.title}" for brand "${brand.companyName || 'Brand'}"`);
  }

  console.log(`\nSuccessfully created and saved ${createdCount} live campaigns to PostgreSQL database!`);
}

